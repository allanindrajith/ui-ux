let activeStyle = "all";
let activePlatform = "all";

const root = document.getElementById("showcase-root");
const lightbox = document.getElementById("lightbox");
const lbImg = document.getElementById("lb-img");
const lbMeta = document.getElementById("lb-meta");
const lbTitle = document.getElementById("lb-title");
const lbDesc = document.getElementById("lb-desc");
const lbTags = document.getElementById("lb-tags");
const lbFigmaLink = document.getElementById("lb-figma-link");

function figmaUrl(fileKey, nodeId) {
  return `https://www.figma.com/design/${fileKey}?node-id=${nodeId}`;
}

function openLightbox(section, project) {
  lbMeta.textContent = `${section.number} · ${section.name} · ${project.platformLabel}`;
  lbTitle.textContent = `${project.title} — ${project.domain}`;
  lbImg.src = project.image;
  lbImg.alt = `${project.title} (${section.name})`;
  lbDesc.textContent = project.description;
  lbFigmaLink.href = figmaUrl(section.figmaFileKey, project.figmaNode);
  lbTags.innerHTML = project.tags.map((t) => `<span class="lb-tag">${t}</span>`).join("");
  lightbox.classList.add("open");
  lightbox.setAttribute("aria-hidden", "false");
  document.body.style.overflow = "hidden";
}

function closeLightbox() {
  lightbox.classList.remove("open");
  lightbox.setAttribute("aria-hidden", "true");
  document.body.style.overflow = "";
}

function render() {
  const sections = DESIGN_SECTIONS.filter((s) => activeStyle === "all" || s.id === activeStyle);

  root.innerHTML = sections
    .map((section) => {
      const visibleProjects = section.projects.filter(
        (p) => activePlatform === "all" || p.platform === activePlatform
      );
      if (!visibleProjects.length) return "";

      const swatches = section.palette
        .map((c) => `<span class="swatch" style="background:${c}" title="${c}"></span>`)
        .join("");

      const cards = visibleProjects
        .map(
          (p) => `
          <article class="project-card">
            <div class="card-preview" data-section="${section.id}" data-node="${p.figmaNode}">
              <span class="platform-badge">${p.platformLabel}</span>
              <img src="${p.image}" alt="${p.title} — ${section.name} UI design" loading="lazy" />
            </div>
            <div class="card-body">
              <div class="card-top">
                <div>
                  <h3 class="card-title">${p.title}</h3>
                  <div class="card-domain">${p.domain}</div>
                </div>
                <button class="preview-btn" data-section="${section.id}" data-node="${p.figmaNode}">Expand</button>
              </div>
              <p class="card-desc">${p.description}</p>
              <div class="card-actions">
                <div style="display:flex;align-items:center;gap:12px;flex-wrap:wrap;">
                  ${p.liveUrl ? `<a class="btn-primary" style="padding:7px 14px;font-size:12px;" href="${p.liveUrl}">Live Prototype ↗</a>` : ""}
                  <a class="card-link" href="${figmaUrl(section.figmaFileKey, p.figmaNode)}" target="_blank" rel="noopener noreferrer">
                    Open in Figma ↗
                  </a>
                </div>
                <span class="lb-tag">${p.tags[0]}</span>
              </div>
            </div>
          </article>
        `
        )
        .join("");

      return `
        <section class="style-section" id="${section.id}">
          <div class="section-header">
            <div>
              <div class="section-num">STYLE ${section.number} / 06</div>
              <h2 class="section-title">${section.name}</h2>
              <p class="section-desc">${section.summary}</p>
            </div>
            <div class="palette-swatches" aria-label="Color palette">${swatches}</div>
          </div>
          <div class="pair-grid ${visibleProjects.length === 1 ? "single-col" : ""}">
            ${cards}
          </div>
        </section>
      `;
    })
    .join("");

  root.querySelectorAll("[data-node]").forEach((el) => {
    el.addEventListener("click", () => {
      const sec = DESIGN_SECTIONS.find((s) => s.id === el.dataset.section);
      const proj = sec?.projects.find((p) => p.figmaNode === el.dataset.node);
      if (sec && proj) openLightbox(sec, proj);
    });
  });
}

document.getElementById("style-filters").addEventListener("click", (e) => {
  const btn = e.target.closest(".filter-chip");
  if (!btn) return;
  activeStyle = btn.dataset.style;
  document.querySelectorAll(".filter-chip").forEach((b) => b.classList.toggle("active", b === btn));
  render();
});

document.getElementById("platform-filters").addEventListener("click", (e) => {
  const btn = e.target.closest(".plat-btn");
  if (!btn) return;
  activePlatform = btn.dataset.platform;
  document.querySelectorAll(".plat-btn").forEach((b) => b.classList.toggle("active", b === btn));
  render();
});

document.getElementById("lightbox-close").addEventListener("click", closeLightbox);
document.getElementById("lightbox-close-bg").addEventListener("click", closeLightbox);
document.addEventListener("keydown", (e) => {
  if (e.key === "Escape" && lightbox.classList.contains("open")) closeLightbox();
});

render();
